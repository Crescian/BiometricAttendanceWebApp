<h3>What this page is for</h3>
<p>
    A permanent record of who did what and when: approvals, edits, uploads, deletions, report
    generation, sign-ins and more. Entries can't be changed or deleted.
</p>

<h3>Find an entry</h3>
<ol>
    <li>Narrow the list with <b>From / To</b>, <b>User</b>, <b>Category</b>, <b>Outcome</b> (Success, Failure,
        Denied) and <b>Search</b>. Click <b>Clear</b> to reset.</li>
    <li>Click <span class="help-btn"><i class="fas fa-eye"></i></span> (View details) on a row to see the
        <b>Before</b> and <b>After</b> values of every changed field.</li>
    <li>In the details, <b>Show all from this request</b> lists everything done in the same action, for
        example every row of a bulk approval.</li>
</ol>

<h3>Verify integrity</h3>
<p>
    <b>Verify integrity</b> checks that no entry was altered or removed since it was written. Each entry is
    chained to the previous one. A failure names the first entry where the chain breaks. Report that
    to IT.
</p>

<h3>Export</h3>
<p><b>Export CSV</b> downloads the entries that match the current filters.</p>

<div class="help-tip">
    <b>Tip:</b> to answer "who approved this overtime?", search the employee's name and filter the
    <b>Category</b> to approvals.
</div>

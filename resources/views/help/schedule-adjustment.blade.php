<h3>What this page is for</h3>
<p>
    Use a <b>schedule adjustment</b> when an employee works a different schedule on specific days, for
    example a temporary night shift. Once <b>approved</b>, that day's overtime is recalculated with the
    adjusted schedule, and the payroll report uses it for that day.
</p>
<p>
    It works on the <b>loaded</b> biometric import (green "Loaded Data" bar). Department heads see their
    own departments. Admins see all.
</p>

<h3>File an adjustment</h3>
<ol>
    <li>Click <span class="help-btn"><i class="fa-solid fa-plus"></i> Add</span>.</li>
    <li>Choose the <b>Employee Name</b>.</li>
    <li>Pick the days under <b>Attendance Dates</b>: <b>Single Date</b>, <b>Multi Dates</b> or <b>Date Range</b>.</li>
    <li>Choose the <b>schedule</b> for those days from the list, and enter the <b>In</b> / <b>Out</b> times if asked.</li>
    <li>Fill in <b>Reasons</b> (and <b>Others</b> if needed), then click <b>Add Schedule Adjustment</b>.</li>
</ol>
<p>New adjustments start as <b>Pending</b>. Days that already have one are skipped and listed.</p>

<h3>Approve or cancel</h3>
<ul>
    <li><span class="help-btn"><i class="fas fa-check"></i> Approve</span> applies the schedule to that day
        and recalculates its overtime. Then review that day on the <b>Overtime</b> page.</li>
    <li><span class="help-btn"><i class="fas fa-xmark"></i> Cancel</span> rejects it.</li>
    <li>Approve many at once with <b>Approve selected</b> or <b>Bulk approve</b> (all, or by department,
        employee or date).</li>
</ul>

<h3>The schedule list</h3>
<p>
    <span class="help-btn"><i class="fa-regular fa-calendar"></i> View Schedule</span> shows the schedules you
    can choose from. To add one, set <b>From Time</b>, <b>To Time</b>, <b>Schedule Type</b> (Day / Night shift,
    with or without break, or compressed) and <b>Schedule Shift</b>, then click <b>Save Changes</b>. Use
    <b>Edit</b> or <b>Delete</b> on an existing schedule.
</p>

<h3>Finding adjustments</h3>
<p>
    Use the filter bar (<b>From / To</b>, <b>Department</b>, <b>Schedule</b>), the <b>Search</b> box and the
    tabs. Click the <b>Employee</b> or <b>Date</b> header to sort.
</p>

<div class="help-tip">
    <b>Temporary or permanent?</b> Use a schedule adjustment for <b>specific days</b>. For a
    <b>permanent</b> change, edit the employee on <b>Employee Management</b> instead.
</div>

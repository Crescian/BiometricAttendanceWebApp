<h3>What this page is for</h3>
<p>
    File and approve employees' leave requests for the <b>loaded</b> biometric import (shown in the
    green "Loaded Data" bar). Department heads see their own departments. Admins see all.
</p>

<h3>File a leave</h3>
<ol>
    <li>Click <span class="help-btn"><i class="fa-solid fa-plus"></i> Add</span>.</li>
    <li>Choose the <b>Employee Name</b>.</li>
    <li>Under <b>Attendance Dates</b>, choose how to pick the days:
        <ul>
            <li><b>Single Date</b>: one day.</li>
            <li><b>Multi Dates</b>: several separate days.</li>
            <li><b>Date Range</b>: every day from one date to another.</li>
        </ul>
    </li>
    <li>For each entry choose <b>Whole Day</b> or <b>Half Day</b>. Use <b>+ Add Leave Type</b> for another entry.</li>
    <li>Fill in <b>Reasons</b> (and <b>Others</b> if needed), then click <b>Add Leave</b>.</li>
</ol>
<p>
    Days that already have a pending or approved leave for that employee are skipped, and a list of
    them is shown. New leaves start as <b>Pending</b>.
</p>

<h3>Approve or cancel</h3>
<ul>
    <li>On the <b>Pending</b> tab, use <span class="help-btn"><i class="fas fa-check"></i> Approve</span>
        or <span class="help-btn"><i class="fas fa-xmark"></i> Cancel</span> on each row.</li>
    <li>To approve many at once, tick rows and use <b>Approve selected</b>, or use <b>Bulk approve</b>
        (all, or by department, employee or date).</li>
    <li>An approved leave can still be cancelled from the <b>Approved</b> tab.</li>
</ul>

<h3>Finding leaves</h3>
<p>
    Use the filter bar (<b>From / To</b>, <b>Department</b>), the <b>Search</b> box, and the tabs. Click
    the <b>Employee</b> or <b>Record Date</b> header to sort.
</p>

<div class="help-warn">
    <b>Good to know:</b> approving a leave records it, but it does <b>not</b> change attendance hours,
    overtime or the payroll report on its own. The <b>With Pay</b> column currently always shows
    <b>No</b>, because the form doesn't set it.
</div>

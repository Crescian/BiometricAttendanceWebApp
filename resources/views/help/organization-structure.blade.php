<h3>What this page is for</h3>
<p>
    Set up the company structure: <b>Business Units</b>, the <b>Companies</b> under them, and the
    <b>Departments</b> under each company, each with its head.
</p>
<div class="help-warn">
    <b>Department heads decide who sees what.</b> A user who is set as a department's <b>Department
    Head</b> sees and approves that department's overtime, leaves, certificates and schedule
    adjustments. Users who head no department see none. The department name must match the
    <b>Department</b> on the employees exactly.
</div>

<h3>Add or change an entry</h3>
<ol>
    <li>Pick the tab: <b>Business Units</b>, <b>Companies</b> or <b>Departments</b>.</li>
    <li>Click <span class="help-btn"><i class="fa-solid fa-plus"></i> Add</span> (the label follows the tab, e.g.
        "Add department").</li>
    <li>Fill in the form:
        <ul>
            <li><b>Business Unit</b>: name and head.</li>
            <li><b>Company</b>: name, company head and its business unit.</li>
            <li><b>Department</b>: name, <b>Department Head</b> (a registered user) and its company.</li>
        </ul>
    </li>
    <li>Click <b>Save</b>. Use <span class="help-btn"><i class="fas fa-pen"></i> Edit</span> or
        <span class="help-btn"><i class="fas fa-trash"></i> Delete</span> on a row to change or remove it.</li>
</ol>

<div class="help-tip">
    <b>New department head?</b> Register them on <b>User Management</b> first, then choose them as the
    Department Head here.
</div>

<h3>What this page is for</h3>
<p>
    A <b>Certificate of Attendance (COA)</b> records attendance for a day the biometric device has no
    record of, for example a forgotten punch, fieldwork or an off-site assignment. Once
    <b>approved</b>, it becomes that day's attendance record (marked <b>COA</b> on the Attendance
    Record page), and the day's overtime is calculated from it.
</p>
<p>
    It works on the <b>loaded</b> biometric import (green "Loaded Data" bar). Department heads see their
    own departments. Admins see all.
</p>

<h3>File a certificate</h3>
<ol>
    <li>Click <span class="help-btn"><i class="fa-solid fa-plus"></i> Add</span>.</li>
    <li>Choose the <b>Employee Name</b>, or <b>All Employees</b> to file the same entry for everyone.</li>
    <li>Pick the days under <b>Attendance Dates</b>: <b>Single Date</b>, <b>Multi Dates</b> or <b>Date Range</b>.</li>
    <li>Under <b>Log Hours</b>, use <b>+ In</b> and <b>+ Out</b> to enter the time in and time out.</li>
    <li>Fill in <b>Reasons</b> (and <b>Others</b> if needed). Tick <b>Is Cutoff</b> if the entry is for a cut-off
        day. This is saved with the certificate for reference.</li>
    <li>Click <b>Add Certificate of Attendance</b>.</li>
</ol>
<p>
    Days where the employee already has attendance are skipped, and a list is shown, because a
    certificate is only for days with no record. New certificates start as <b>Pending</b>.
</p>

<h3>Approve or cancel</h3>
<ul>
    <li>On the <b>Pending</b> tab, click <span class="help-btn"><i class="fas fa-check"></i> Approve</span> to create
        the attendance record and calculate that day's overtime. The overtime still needs approving
        on the <b>Overtime</b> page.</li>
    <li><span class="help-btn"><i class="fas fa-xmark"></i> Cancel</span> rejects the certificate.</li>
    <li>Approve many at once with <b>Approve selected</b> (ticked rows) or <b>Bulk approve</b> (all, or by
        department, employee or date).</li>
</ul>

<h3>Finding certificates</h3>
<p>
    Use the filter bar (<b>From / To</b>, <b>Department</b>, <b>Schedule</b>), the <b>Search</b> box and the
    tabs. Click the <b>Employee</b> or <b>Date</b> header to sort.
</p>

<div class="help-tip">
    <b>Tip:</b> approve certificates <b>before</b> approving overtime and generating payroll, so the new
    days' hours are included.
</div>

<h3>What this page is for</h3>
<p>
    A quick overview of the <b>loaded</b> biometric import (green "Loaded Data" bar) and the upcoming
    holidays.
</p>
<ul>
    <li><b>My Stuff</b>: present, late and on-leave totals for your scope, plus recent certificates,
        items <b>pending approval</b> and recent clock-ins / outs. Department heads see their own
        departments. Admins see everyone.</li>
    <li><b>Charts</b>: the status of leaves, schedule adjustments and certificates, and total presents.</li>
    <li><b>Holidays</b>: this month's holidays (earlier days of the month are dimmed). Holidays for other months are still saved and used for overtime and payroll; when this month has none, the card names the next one.</li>
</ul>

<h3>Add a holiday</h3>
<ol>
    <li>In the <b>Holidays</b> card, click <span class="help-btn"><i class="fa-solid fa-plus"></i> Add</span>.</li>
    <li>Enter a <b>Title</b> (e.g. "Independence Day") and the <b>Record Date</b>.</li>
    <li>Choose the <b>Holiday Type</b>:
        <ul>
            <li><b>Regular Holiday</b>: paid in the LH (legal holiday) columns.</li>
            <li><b>Special Non-Working Holiday</b>: paid in the SH columns.</li>
            <li><b>Others</b>: any other non-working day. It's paid like a rest day, in the RD columns.</li>
        </ul>
    </li>
    <li>Click <b>Add Holiday</b>. Use <span class="help-btn"><i class="fas fa-pen"></i></span> or
        <span class="help-btn"><i class="fas fa-trash"></i></span> on a holiday to change or remove it.</li>
</ol>
<p>Sundays are already listed as <b>Rest Day</b>.</p>

<div class="help-warn">
    <b>Add holidays before uploading</b> the biometric file for those dates. Overtime, including
    rest-day and holiday hours, is calculated at upload. A holiday added afterwards doesn't
    recalculate overtime that already exists.
</div>

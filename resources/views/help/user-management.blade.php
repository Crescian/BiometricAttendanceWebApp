<h3>What this page is for</h3>
<p>
    Control who can sign in and what they can do. Users sign in with their <b>ticketing system</b>
    account, so a person needs an account there and a registration here.
</p>
<ul>
    <li><b>Admin</b>: everything, including uploads, employees, reports, users and the audit log.</li>
    <li><b>Department Head</b>: the approval pages for the departments they head.</li>
</ul>

<h3>Register a user</h3>
<ol>
    <li>Click <span class="help-btn"><i class="fa-solid fa-plus"></i> Add</span>.</li>
    <li>In <b>Find Person</b>, search the ticketing directory by name or email and pick the person. Their
        name and email fill in. If the directory is unavailable, type them in.</li>
    <li>Choose the <b>Role</b>: <b>Department Head</b> or <b>Admin</b>.</li>
    <li>Click <b>Save</b>.</li>
</ol>
<p>
    Then, for a department head, open <b>Organization Structure</b> and set them as the
    <b>Department Head</b> of their department(s). That's what gives them access to its records.
</p>

<h3>Edit, deactivate or activate</h3>
<ul>
    <li><span class="help-btn"><i class="fas fa-pen"></i> Edit</span>: change the role, <b>Position</b> or <b>Status</b>.</li>
    <li><b>Deactivate</b> / <b>Activate</b>: an <b>Inactive</b> user can't sign in. Use this when someone
        leaves, instead of removing them, so their history stays.</li>
</ul>

<h3>Reading the list</h3>
<p>
    <b>Presence</b> shows who is online now. <b>Joined</b> is when they were registered. Click the <b>User</b>
    or <b>Joined</b> header to sort.
</p>
